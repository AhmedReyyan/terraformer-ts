import { spawn } from 'child_process';
import * as fs from 'fs/promises';
import * as path from 'path';
import { GENERATED_FILE } from './hcl-generator';

export interface TerraformRunResult {
  exitCode: number;
  stdout: string;
  stderr: string;
}

export interface GenerateConfigResult {
  success: boolean;
  /** True when generated.tf was written (it can be written even when plan reports errors). */
  generatedFile: boolean;
  message: string;
}

/** Minimum version with `import` blocks and `-generate-config-out`. */
const MIN_VERSION: [number, number] = [1, 5];

export class TerraformCli {
  constructor(private binary: string = 'terraform', private env: Record<string, string> = {}) {}

  /** Returns the version string if a usable Terraform (>= 1.5) is installed, otherwise null. */
  async detectVersion(): Promise<string | null> {
    try {
      const result = await this.run(['version', '-json'], process.cwd());
      if (result.exitCode !== 0) {
        return null;
      }
      const version: string = JSON.parse(result.stdout).terraform_version;
      const [major, minor] = version.split('.').map(Number);
      if (major > MIN_VERSION[0] || (major === MIN_VERSION[0] && minor >= MIN_VERSION[1])) {
        return version;
      }
      return null;
    } catch {
      return null;
    }
  }

  /**
   * Run `terraform init` and `terraform plan -generate-config-out=generated.tf` in a
   * directory that contains provider and import blocks. Plan is read-only: it refreshes
   * the imported objects but never changes infrastructure.
   */
  async generateConfig(directory: string, pluginCacheDir?: string): Promise<GenerateConfigResult> {
    const generatedPath = path.join(directory, GENERATED_FILE);
    await removePreviousGeneratedFile(generatedPath);

    const env: Record<string, string> = {};
    if (pluginCacheDir && !process.env.TF_PLUGIN_CACHE_DIR) {
      await fs.mkdir(pluginCacheDir, { recursive: true });
      env.TF_PLUGIN_CACHE_DIR = pluginCacheDir;
    }

    const init = await this.run(['init', '-input=false', '-no-color'], directory, env);
    await writeLog(directory, 'init', init);
    if (init.exitCode !== 0) {
      return {
        success: false,
        generatedFile: false,
        message: `terraform init failed (see terraform-init.log): ${lastLines(init.stderr || init.stdout)}`
      };
    }

    const plan = await this.run(
      ['plan', '-input=false', '-no-color', `-generate-config-out=${GENERATED_FILE}`],
      directory,
      env
    );
    await writeLog(directory, 'plan', plan);
    const generatedFile = await exists(generatedPath);

    if (plan.exitCode === 0) {
      return { success: true, generatedFile, message: 'configuration generated' };
    }
    return {
      success: false,
      generatedFile,
      message: generatedFile
        ? `generated.tf was written but terraform plan reported errors that need manual fixes (see terraform-plan.log): ${lastLines(plan.stderr)}`
        : `terraform plan failed (see terraform-plan.log): ${lastLines(plan.stderr || plan.stdout)}`
    };
  }

  run(args: string[], cwd: string, extraEnv: Record<string, string> = {}): Promise<TerraformRunResult> {
    return new Promise((resolve, reject) => {
      const child = spawn(this.binary, args, {
        cwd,
        env: { ...process.env, ...this.env, ...extraEnv, TF_IN_AUTOMATION: '1' },
        stdio: ['ignore', 'pipe', 'pipe'],
        windowsHide: true
      });
      let stdout = '';
      let stderr = '';
      child.stdout.on('data', chunk => { stdout += chunk; });
      child.stderr.on('data', chunk => { stderr += chunk; });
      child.on('error', reject);
      child.on('close', code => resolve({ exitCode: code ?? 1, stdout, stderr }));
    });
  }
}

async function removePreviousGeneratedFile(generatedPath: string): Promise<void> {
  // Terraform refuses to overwrite an existing file. Only remove it if Terraform wrote it.
  try {
    const content = await fs.readFile(generatedPath, 'utf8');
    if (content.startsWith('# __generated__ by Terraform')) {
      await fs.rm(generatedPath);
    } else {
      throw new Error(`${generatedPath} exists and was not generated by Terraform; refusing to overwrite it`);
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
      throw error;
    }
  }
}

async function writeLog(directory: string, step: string, result: TerraformRunResult): Promise<void> {
  await fs.writeFile(
    path.join(directory, `terraform-${step}.log`),
    `exit code: ${result.exitCode}\n\n--- stdout ---\n${result.stdout}\n--- stderr ---\n${result.stderr}`,
    'utf8'
  );
}

async function exists(filePath: string): Promise<boolean> {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

/** Summarise Terraform output: its "Error:" lines if there are any, otherwise the last lines. */
function lastLines(text: string, count: number = 5): string {
  const lines = text.trim().split(/\r?\n/).map(line => line.replace(/^[\s│╷╵]+/, '').trim()).filter(Boolean);
  const errors = [...new Set(lines.filter(line => line.startsWith('Error:')))];
  const picked = errors.length > 0 ? errors : lines.slice(-count);
  const more = errors.length > count ? ` (+${errors.length - count} more)` : '';
  return picked.slice(0, count).join(' | ') + more;
}
